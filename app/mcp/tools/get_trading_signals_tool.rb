# frozen_string_literal: true

class GetTradingSignalsTool < ApplicationMCPTool
  INDICES = %w[NIFTY BANKNIFTY SENSEX].freeze

  SIGNAL_FIELDS = %w[
    id index_key direction timeframe confidence_score
    supertrend_value adx_value signal_timestamp
  ].freeze

  tool_name 'get_trading_signals'
  description 'Recent trading signals generated by the signal engine, newest first, plus the current setup decision. Read-only.'

  property :index, type: 'string', description: 'Filter by index; omit for all', enum: INDICES
  property :limit, type: 'integer', description: 'Max signals to return (default 20, max 100)'

  def perform
    snapshot = market_snapshot
    signals = TradingSignal.recent(24)
    signals = signals.for_index(index) if index.present?
    signals = signals.order(signal_timestamp: :desc).limit((limit || 20).to_i.clamp(1, 100))

    render_json(
      generated_at: snapshot['generated_at'],
      mode: snapshot['mode'],
      setup: snapshot['setup'],
      signals: signals.map { |s| s.attributes.slice(*SIGNAL_FIELDS) }
    )
  end
end
